-- Which products generated more than ₹100,000 in completed sales,
-- and what were their total sales?

SELECT product,
       SUM(total_sales) AS product_sales
FROM sales
WHERE status = 'Completed'
GROUP BY product
HAVING SUM(total_sales) > 100000
ORDER BY product_sales DESC;

-- How much completed sales did each product generate in each city, ranked from highest to lowest?

SELECT city,
       product,
       SUM(total_sales) AS product_sales
FROM sales
WHERE status = 'Completed'
GROUP BY city, product
ORDER BY product_sales DESC;

-- Which 5 customers generated the highest completed sales?

SELECT customer_name,
       SUM(total_sales) AS customer_sales
FROM sales
WHERE status = 'Completed'
GROUP BY customer_name
ORDER BY customer_sales DESC
LIMIT 5;

-- How much completed sales did the business generate in each month, in chronological order?

SELECT TO_CHAR(date, 'Month') AS month,
       SUM(total_sales) AS monthly_sales
FROM sales
WHERE status = 'Completed'
GROUP BY TO_CHAR(date, 'Month'),
         EXTRACT(MONTH FROM date)
ORDER BY EXTRACT(MONTH FROM date) ASC;

-- How much completed sales did each product category generate
-- in each city, ranked from highest to lowest?

SELECT city,
       category,
       SUM(total_sales) AS category_sales
FROM sales
WHERE status = 'Completed'
GROUP BY city, category
ORDER BY category_sales DESC;

-- How many completed transactions and how much completed
-- sales were generated through each payment method?

SELECT payment_method,
       COUNT(transaction_id) AS total_transaction,
       SUM(total_sales) AS transaction_sales
FROM sales
WHERE status = 'Completed'
GROUP BY payment_method
ORDER BY transaction_sales DESC;

-- How many transactions are in each status, and what is
-- the total sales value associated with each status?

SELECT status,
       COUNT(transaction_id) AS status_transaction,
       SUM(total_sales) AS status_sales
FROM sales
GROUP BY status
ORDER BY status_sales DESC;

-- How can we classify each transaction based on its sales value as Low, Medium, or High?

SELECT transaction_id,
       product,
       total_sales,
       CASE
           WHEN total_sales >= 50000 THEN 'High'
           WHEN total_sales >= 20000 THEN 'Medium'
           ELSE 'Low'
       END AS sales_category
FROM sales;

-- Which products sold the highest number of units, ranked from highest to lowest?

SELECT product,
       SUM(quantity) AS total_quantity
FROM sales
GROUP BY product
ORDER BY total_quantity DESC;

-- What is the average sales amount per transaction in each city?

SELECT city,
       SUM(total_sales) / COUNT(transaction_id) AS avg_order_value
FROM sales
GROUP BY city
ORDER BY avg_order_value DESC;

-- Which 5 completed transactions generated the highest sales value?

SELECT transaction_id,
       customer_name,
       product,
       city,
       total_sales
FROM sales
WHERE status = 'Completed'
ORDER BY total_sales DESC
LIMIT 5;

-- Which products generated the most completed sales,
-- and how many transactions contributed to those sales?

SELECT product,
       SUM(total_sales) AS product_sales,
       COUNT(transaction_id) AS product_transaction
FROM sales
