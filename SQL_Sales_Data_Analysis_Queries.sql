ORDER BY max_sales DESC;

-- What is the lowest single transaction value recorded for each product, ranked from lowest to highest?

SELECT product,
       MIN(total_sales) AS min_sales
FROM sales
GROUP BY product
ORDER BY min_sales ASC;

