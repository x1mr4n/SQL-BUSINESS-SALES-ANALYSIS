CREATE TABLE sales (
    transaction_id INT PRIMARY KEY,
    date DATE,
    customer_name VARCHAR(100),
    city VARCHAR(50),
    category VARCHAR(50),
    product VARCHAR(50),
    quantity INT,
    unit_price NUMERIC(10,2),
    total_sales NUMERIC(12,2),
    payment_method VARCHAR(30),
    status VARCHAR(30)
);

-- How many sales transactions are recorded in the dataset?

SELECT COUNT(*)
FROM sales;

-- What are the details of all sales transactions recorded in the dataset?

SELECT *
FROM sales;

-- What are the customers, their cities, and the sales amount associated with each transaction?

SELECT customer_name,city,total_sales
FROM sales;

-- What products were sold, in what quantities, and what was the sales amount for each transaction?

SELECT product,quantity,total_sales
FROM sales;

-- What sales transactions were recorded in Delhi?

SELECT * FROM sales
WHERE city = 'Delhi';

-- What sales transactions involved laptops?

SELECT *
FROM sales
WHERE product = 'Laptop';

-- What sales transactions were paid for using UPI?

SELECT * FROM sales
WHERE payment_method = 'UPI';

-- What are the total sales generated by each product?	

SELECT product,
SUM (total_sales) AS product_sales
FROM sales
GROUP BY product
ORDER BY product_sales DESC;

-- What are the top 5 highest-value transactions by sales amount?

SELECT transaction_id, product, city, total_sales
FROM sales
ORDER BY total_sales DESC
LIMIT 5;

-- What are the transactions ranked from highest to lowest by sales amount?

SELECT transaction_id, product, city, total_sales
FROM sales
ORDER BY total_sales DESC;

-- How many transactions did each product have?

SELECT product,
    COUNT(transaction_id) AS transaction_count
FROM sales
GROUP BY product
ORDER BY transaction_count DESC;

-- What is the average sales amount for each product?

SELECT product,
    AVG(total_sales) AS average_sales
FROM sales
GROUP BY product
ORDER BY average_sales DESC;

-- What was the highest-value individual transaction?

SELECT MAX(total_sales) AS highest_transaction
FROM sales;

-- What was the lowest-value individual transaction?

SELECT MIN(total_sales) AS lowest_transaction
FROM sales;

-- Which products generated more than ₹1,00,000 in total sales?

SELECT product,
       SUM(total_sales) AS product_sales
FROM sales
GROUP BY product
HAVING SUM(total_sales) > 100000
ORDER BY product_sales DESC;

-- How can we classify products according to their total sales performance?

SELECT product,
       SUM(total_sales) AS product_sales,
       CASE
           WHEN SUM(total_sales) >= 100000 THEN 'High'
           WHEN SUM(total_sales) >= 50000 THEN 'Medium'
           ELSE 'Low'
       END AS sales_category
FROM sales
GROUP BY product
ORDER BY product_sales DESC;

-- Among completed transactions in Delhi, which products generated more than ₹50,000
-- in total sales? Show the products from highest to lowest total sales.

SELECT product,
       SUM(total_sales) AS product_sales
FROM sales
WHERE city = 'Delhi'
  AND status = 'Completed'
GROUP BY product
HAVING SUM(total_sales) > 50000
ORDER BY product_sales DESC;

-- What are the total completed sales for each month?

SELECT TO_CHAR(date, 'Month') AS month,
       SUM(total_sales) AS monthly_sales
FROM sales
WHERE status = 'Completed'
GROUP BY month
ORDER BY monthly_sales DESC;

-- What are the total completed sales for each month, 
-- presented in chronological order from January to December?

SELECT TO_CHAR(date, 'Month') AS month,
       SUM(total_sales) AS monthly_sales
FROM sales
WHERE status = 'Completed'
GROUP BY TO_CHAR(date, 'Month'), EXTRACT(MONTH FROM date)
ORDER BY EXTRACT(MONTH FROM date);

-- How do completed sales vary across different product categories each month?

SELECT TO_CHAR(date, 'Month') AS month,
     category,
       SUM(total_sales) AS monthly_sales
FROM sales
WHERE status = 'Completed'
GROUP BY month, category, EXTRACT(MONTH FROM date)
ORDER BY EXTRACT(MONTH FROM date);

-- How many unique cities are represented in the sales dataset?

SELECT COUNT(DISTINCT city) AS unique_cities
FROM sales;

